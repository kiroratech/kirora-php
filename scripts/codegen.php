function q(string $value): string
{
    return "'" . addcslashes($value, "'\\") . "'";
}

/** The node a local `$ref`, such as `#/components/schemas/Contact`, points to. */
function deref(array $spec, string $ref): mixed
{
    $node = $spec;
    foreach (array_slice(explode('/', $ref), 1) as $key) {
        $node = $node[str_replace(['~1', '~0'], ['/', '~'], $key)] ?? fail("Unresolvable \$ref $ref");
    }

    return $node;
}

function resolve(array $spec, mixed $value): mixed
{
    while (is_array($value) && isset($value['$ref']) && is_string($value['$ref'])) {
        $value = deref($spec, $value['$ref']);
    }

    return $value;
}

/** A SNAKE_CASE or dotted.name as a PascalCase enum case. */
function caseName(string $value): string
{
    $words = preg_split('/[^A-Za-z0-9]+/', strtolower($value), -1, PREG_SPLIT_NO_EMPTY);
    $name = implode('', array_map('ucfirst', $words));

    return preg_match('/^\d/', $name) ? "_$name" : $name;
}

/** The first paragraph of a description, on one line, safe inside a docblock. */
function summary(?string $text): string
{
    if ($text === null || trim($text) === '') {
        return '';
    }
    $paragraph = preg_split('/\n\s*\n/', trim($text))[0];

    return str_replace('*/', '*&#47;', trim((string) preg_replace('/\s+/', ' ', $paragraph)));
}

function stringEnum(string $name, string $description, array $values, string $what): string
{
    $cases = '';
    foreach ($values as $value) {
        $cases .= '    case ' . caseName($value) . ' = ' . q($value) . ";\n";
    }

    $header = HEADER;

    return <<<PHP
<?php

$header

declare(strict_types=1);

namespace Kirora\Enums;

/**
 * $description
 *
 * A value added to the API after this version of the SDK still comes through, as a
 * string: check it with `isKnown()`.
 */
enum $name: string
{
$cases
    /**
     * Whether this version of the SDK knows the $what.
     */
    public static function isKnown(string \$value): bool
    {
        return self::tryFrom(\$value) !== null;
    }
}

PHP;
}

/**
 * The paths, such as `properties` or `events.*.event.properties`, of the fields in a body
 * that can only be a JSON object. PHP's empty array is sent as `{}` there, since `[]` and
 * `{}` are both `[]` in PHP. `*` stands for every entry of an array or map.
 *
 * @param  array<string, true>  $out
 * @param  list<string>  $seen
 */
function objectPaths(array $spec, mixed $schema, string $prefix, array $seen, array &$out): void
{
    if (! is_array($schema)) {
        return;
    }
    if (isset($schema['$ref'])) {
        // Stops at a schema already on this path, so a recursive one ends, at any depth.
        if (in_array($schema['$ref'], $seen, true)) {
            return;
        }
        objectPaths($spec, deref($spec, $schema['$ref']), $prefix, [...$seen, $schema['$ref']], $out);

        return;
    }
    // Every shape the value can take, so a field that may be an array too is left alone.
    $members = [];
    foreach (['anyOf', 'oneOf', 'allOf'] as $keyword) {
        foreach ($schema[$keyword] ?? [] as $member) {
            $members[] = $member;
        }
    }
    $types = [];
    foreach ([$schema, ...$members] as $shape) {
        $shape = resolve($spec, $shape);
        if (! is_array($shape)) {
            continue;
        }
        foreach ((array) ($shape['type'] ?? []) as $type) {
            $types[$type] = true;
        }
        if (! isset($shape['type']) && (isset($shape['properties']) || isset($shape['additionalProperties']))) {
            $types['object'] = true;
        }
    }
    unset($types['null']);
    if ($prefix !== '' && array_keys($types) === ['object']) {
        $out[$prefix] = true;
    }
    $join = fn (string $name) => $prefix === '' ? $name : "$prefix.$name";
    foreach ($members as $member) {
        objectPaths($spec, $member, $prefix, $seen, $out);
    }
    foreach ($schema['properties'] ?? [] as $name => $property) {
        objectPaths($spec, $property, $join((string) $name), $seen, $out);
    }
    if (is_array($schema['additionalProperties'] ?? null)) {
        objectPaths($spec, $schema['additionalProperties'], $join('*'), $seen, $out);
    }
    if (is_array($schema['items'] ?? null)) {
        objectPaths($spec, $schema['items'], $join('*'), $seen, $out);
    }
}

/**
 * How each operation in the whole spec may be retried, so `Client::request()` retries an
 * endpoint without a service method as its method would.
 */
function operationsFile(array $spec): string
{
    foreach (RETRY_KINDS as $kind) {
        if (! isset($spec['x-retry-kinds'][$kind])) {
            fail("x-retry-kinds no longer has \"$kind\": update src/Retry.php and RETRY_KINDS");
        }
    }
    $paths = array_keys($spec['paths']);
    sort($paths);
    $lines = [];
    foreach ($paths as $path) {
        $item = $spec['paths'][$path];
        foreach (['get', 'put', 'post', 'patch', 'delete'] as $method) {
            $operation = $item[$method] ?? null;
            if (! is_array($operation)) {
                continue;
            }
            $retry = $operation['x-retry'] ?? ($method === 'get' ? 'read' : null);
            if ($retry !== null && ! in_array($retry, RETRY_KINDS, true)) {
                fail("$method $path: unknown x-retry \"$retry\": update src/Retry.php");
            }
            // A parameter can be declared on the path, for all its operations, or on one.
            $parameters = array_map(
                fn ($p) => resolve($spec, $p),
                array_merge($item['parameters'] ?? [], $operation['parameters'] ?? []),
            );
            $acceptsKey = false;
            foreach ($parameters as $p) {
                if (($p['in'] ?? null) === 'header' && strtolower($p['name'] ?? '') === 'idempotency-key') {
                    $acceptsKey = true;
                }
            }
            $requestBody = resolve($spec, $operation['requestBody'] ?? null);
            $body = resolve($spec, $requestBody['content']['application/json']['schema'] ?? null);
            $properties = is_array($body) ? ($body['properties'] ?? []) : [];

            $entries = null;
            if ($retry === 'entries') {
                $names = array_keys($properties);
                sort($names);
                foreach ($names as $name) {
                    $property = resolve($spec, $properties[$name]);
                    $items = resolve($spec, $property['items'] ?? null);
                    if (($property['type'] ?? null) === 'array' && isset($items['properties']['idempotencyKey'])) {
                        $entries = $name;
                        break;
                    }
                }
                if ($entries === null) {
                    fail("$method $path: x-retry is entries, but no array in its body has idempotencyKey");
                }
            }

            // The index, in the path split on "/", of the id the operation looks a contact up
            // by, when its body can change that same value.
            $lookupSegment = 0;
            foreach ($parameters as $p) {
                if (($p['in'] ?? null) !== 'query' || ($p['name'] ?? null) !== 'idType') {
                    continue;
                }
                foreach (resolve($spec, $p['schema'] ?? [])['enum'] ?? [] as $value) {
                    if ($value !== 'id' && isset($properties[$value])) {
                        foreach (explode('/', $path) as $index => $segment) {
                            if (str_starts_with($segment, '{')) {
                                $lookupSegment = $index;
                                break 3;
                            }
                        }
                    }
                }
            }

            $objects = [];
            objectPaths($spec, $requestBody['content']['application/json']['schema'] ?? null, '', [], $objects);
            $objects = array_keys($objects);
            sort($objects);

            $noContent = true;
            foreach ($operation['responses'] ?? [] as $code => $response) {
                if (str_starts_with((string) $code, '2') && isset(resolve($spec, $response)['content'])) {
                    $noContent = false;
                }
            }

            $lines[] = sprintf(
                "        %s => ['id' => %s, 'retry' => %s, 'acceptsKey' => %s, 'entries' => %s, 'lookupSegment' => %d, 'noContent' => %s, 'objects' => [%s]],\n",
                q(strtoupper($method) . ' ' . $path),
                q($operation['operationId']),
                $retry === null ? 'null' : q($retry),
                $acceptsKey ? 'true' : 'false',
                $entries === null ? 'null' : q($entries),
                $lookupSegment,
                $noContent ? 'true' : 'false',
                implode(', ', array_map('q', $objects)),
            );
        }
    }
    $kinds = implode(', ', array_map('q', RETRY_KINDS));
    $header = HEADER;
    $body = implode('', $lines);

    return <<<PHP
<?php

$header

declare(strict_types=1);

namespace Kirora;

/**
 * How each endpoint of the API may be retried, by method and path template.
 *
 * @internal
 */
final class Operations
{
    public const RETRY_KINDS = [$kinds];

    /**
     * @var array<string, array{id: string, retry: ?string, acceptsKey: bool, entries: ?string, lookupSegment: int, noContent: bool, objects: list<string>}>
     */
    public const ALL = [
$body    ];
}

PHP;
}

/** Generates a Resource class for each object schema the service methods return. */
final class Models
{
    /** @var array<string, string> schema name => PHP class name */
    private array $classes = [];

    /** @var list<string> */
    private array $queue = [];

    public function __construct(private readonly array $spec)
    {
    }

    /** @return array<string, string> file name => contents */
    public function generate(array $operationIds): array
    {
        $found = [];
        foreach ($this->spec['paths'] as $path => $item) {
            foreach ($item as $method => $operation) {
                if (! is_array($operation) || ! in_array($operation['operationId'] ?? null, $operationIds, true)) {
                    continue;
                }
                $found[] = $operation['operationId'];
                foreach ($operation['responses'] ?? [] as $code => $response) {
                    if (! str_starts_with((string) $code, '2')) {
                        continue;
                    }
                    $schema = resolve($this->spec, resolve($this->spec, $response)['content']['application/json']['schema'] ?? null);
                    $data = $schema['properties']['data'] ?? null;
                    if ($data === null) {
                        continue;
                    }
                    $ref = $data['$ref'] ?? ($data['items']['$ref'] ?? null);
                    if ($ref === null || ! $this->isModel($ref)) {
                        fail("$method $path: its `data` isn't a schema, or an array of one, that the SDK can make a model of");
                    }
                    $this->className($ref);
                }
            }
        }
        $missing = array_diff($operationIds, $found);
        if ($missing !== []) {
            fail('Not in the spec: ' . implode(', ', $missing));
        }

        $files = [];
        while (($ref = array_shift($this->queue)) !== null) {
            $files[$this->classes[$ref] . '.php'] = $this->file($ref);
        }
        ksort($files);

        return $files;
    }

    private function isModel(string $ref): bool
    {
        $schema = resolve($this->spec, ['$ref' => $ref]);

        return is_array($schema)
            && isset($schema['properties'])
            && ! isset($schema['oneOf'])
            && ! isset($schema['anyOf'])
            && (($schema['type'] ?? 'object') === 'object');
    }

    /** The model class for a schema, queueing it to be generated. */
    private function className(string $ref): string
    {
        if (! isset($this->classes[$ref])) {
            $name = basename($ref);
            if (! preg_match('/^[A-Za-z_][A-Za-z0-9_]*$/', $name)) {
                fail("$ref isn't a name PHP allows for a class");
            }
            if (in_array(strtolower($name), RESERVED, true)) {
                $name .= 'Model';
            }
            if (in_array($name, $this->classes, true)) {
                fail("Two schemas would both be the model class $name");
            }
            $this->classes[$ref] = $name;
            $this->queue[] = $ref;
        }

        return $this->classes[$ref];
    }

    private function file(string $ref): string
    {
        $schema = resolve($this->spec, ['$ref' => $ref]);
        $class = $this->classes[$ref];
        $required = $schema['required'] ?? [];
        $lines = [];
        $casts = [];
        foreach ($schema['properties'] as $name => $property) {
            [$type, $cast] = $this->type($property, true, []);
            if (! in_array($name, $required, true) && ! in_array('null', explode('|', $type), true) && $type !== 'mixed') {
                $type .= '|null';
            }
            if ($cast !== null) {
                $casts[] = '        ' . q($name) . ' => ' . $cast . ",\n";
            }
            // A property PHP can't name is still there with $model['name'].
            if (! preg_match('/^[A-Za-z_][A-Za-z0-9_]*$/', $name)) {
                continue;
            }
            $description = summary($this->description($property));
            $lines[] = rtrim(" * @property-read $type \$$name $description");
        }
        $description = summary($schema['description'] ?? $schema['title'] ?? null) ?: "The {$class} object.";
        $docLines = implode("\n", $lines);
        $castsBody = $casts === [] ? '' : "\n" . implode('', $casts) . '    ';
        $header = HEADER;

        return <<<PHP
<?php

$header

declare(strict_types=1);

namespace Kirora\Models;

use Kirora\Resource;

/**
 * $description
 *
$docLines
 */
class $class extends Resource
{
    protected const CASTS = [$castsBody];
}

PHP;
    }

    /**
     * A property's description, else that of the one schema it can be besides null, so
     * `anyOf: [{$ref: X}, {type: null}]` is described by X.
     */
    private function description(mixed $property): ?string
    {
        $own = resolve($this->spec, $property);
        if (! is_array($own)) {
            return null;
        }
        $description = $own['description'] ?? (is_array($property) ? ($property['description'] ?? null) : null);
        if ($description !== null) {
            return $description;
        }
        foreach (['anyOf', 'oneOf'] as $keyword) {
            $nonNull = array_values(array_filter(
                $own[$keyword] ?? [],
                fn ($m) => ! (is_array($m) && ($m['type'] ?? null) === 'null'),
            ));
            if (count($nonNull) === 1) {
                return resolve($this->spec, $nonNull[0])['description'] ?? null;
            }
        }

        return null;
    }

    /**
     * The PHPDoc type of a schema, and how to turn its JSON into models, as PHP source, or
     * null to leave it as decoded. Models are only named where they're cast to, so a union
     * of several models stays an array.
     *
     * @return array{0: string, 1: ?string}
     */
    private function type(mixed $schema, bool $cast, array $seen): array
    {
        if ($schema === true || $schema === [] || ! is_array($schema)) {
            return ['mixed', null];
        }
        if (isset($schema['$ref'])) {
            $ref = $schema['$ref'];
            if ($this->isModel($ref)) {
                if (! $cast) {
                    return ['array<string, mixed>', null];
                }
                $class = $this->className($ref);

                return [$class, "$class::class"];
            }
            if (in_array($ref, $seen, true)) {
                return ['mixed', null];
            }

            return $this->type(deref($this->spec, $ref), $cast, [...$seen, $ref]);
        }
        foreach (['anyOf', 'oneOf'] as $keyword) {
            if (isset($schema[$keyword])) {
                $members = $schema[$keyword];
                $nonNull = array_values(array_filter($members, fn ($m) => ! (is_array($m) && ($m['type'] ?? null) === 'null')));
                $nullable = count($nonNull) < count($members);
                if (count($nonNull) === 1) {
                    [$type, $castSpec] = $this->type($nonNull[0], $cast, $seen);

                    return [$nullable ? self::union([$type, 'null']) : $type, $castSpec];
                }
                $types = array_map(fn ($m) => $this->type($m, false, $seen)[0], $members);

                return [self::union($types), null];
            }
        }
        if (isset($schema['allOf'])) {
            return count($schema['allOf']) === 1
                ? $this->type($schema['allOf'][0], $cast, $seen)
                : ['array<string, mixed>', null];
        }
        if (array_key_exists('const', $schema)) {
            return [self::scalar(get_debug_type($schema['const'])), null];
        }
        $types = (array) ($schema['type'] ?? []);
        if ($types === [] && isset($schema['enum'])) {
            $types = array_unique(array_map(fn ($v) => get_debug_type($v), $schema['enum']));
        }
        if ($types === []) {
            return [isset($schema['properties']) ? 'array<string, mixed>' : 'mixed', null];
        }
        $out = [];
        $castSpec = null;
        foreach ($types as $type) {
            if ($type === 'array') {
                [$item, $itemCast] = $this->type($schema['items'] ?? true, $cast, $seen);
                $out[] = "list<$item>";
                $castSpec = $itemCast === null ? null : "['list' => $itemCast]";
            } elseif ($type === 'object') {
                $additional = $schema['additionalProperties'] ?? true;
                if (isset($schema['properties']) || $additional === true || $additional === false) {
                    $out[] = 'array<string, mixed>';
                } else {
                    [$value, $valueCast] = $this->type($additional, $cast, $seen);
                    $out[] = "array<string, $value>";
                    $castSpec = $valueCast === null ? null : "['map' => $valueCast]";
                }
            } else {
                $out[] = self::scalar($type);
            }
        }
        // A cast only applies when the value can be nothing else but null.
        if (count(array_diff($out, ['null'])) > 1) {
            $castSpec = null;
        }

        return [self::union($out), $castSpec];
    }

    private static function scalar(string $type): string
    {
        return match ($type) {
            'string' => 'string',
            'integer', 'int' => 'int',
            'number', 'float' => 'int|float',
            'boolean', 'bool' => 'bool',
            'null' => 'null',
            default => 'mixed',
        };
    }

    /** @param list<string> $types */
    private static function union(array $types): string
    {
        $parts = [];
        foreach ($types as $type) {
            // Splits only on the top level, so `list<string|null>` stays one member.
            foreach (preg_split('/\|(?![^<]*>)/', $type) as $part) {
                $parts[$part] = true;
            }
        }
        if (isset($parts['mixed'])) {
            return 'mixed';
        }
        $null = isset($parts['null']);
        unset($parts['null']);
        $members = array_keys($parts);
        if ($null) {
            $members[] = 'null';
        }

        return implode('|', $members);
    }
}

