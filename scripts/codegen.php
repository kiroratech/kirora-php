/**
 * Regenerates the models, error codes, webhook event names and how each operation may be
 * retried from Kirora's OpenAPI spec:
 *
 *   composer codegen [-- path/to/openapi.json]
 *   composer codegen:check [-- path/to/openapi.json]
 *
 * By default the spec is downloaded from the commit of github.com/kiroratech/openapi
 * named in `spec/source.json`, and must match its `version` and `sha256`. A local path,
 * or KIRORA_OPENAPI_SPEC, is used instead without those checks, for trying out a spec
 * that isn't published yet. With `--check`, nothing is written: it exits with 1 if any
 * generated file is out of date.
 *
 * A download is cached in `.cache/openapi`, under its checksum, so later runs work
 * offline.
 */

declare(strict_types=1);

$root = dirname(__DIR__);
$args = array_slice($argv, 1);
$check = in_array('--check', $args, true);
$specArg = array_values(array_filter($args, fn (string $arg) => $arg !== '--check'))[0]
    ?? (getenv('KIRORA_OPENAPI_SPEC') ?: null);
$source = json_decode((string) file_get_contents("$root/spec/source.json"), true, 512, JSON_THROW_ON_ERROR);

function fail(string $message): never
{
    fwrite(STDERR, $message . "\n");
    exit(1);
}

$cacheDir = "$root/.cache/openapi";
$cached = "$cacheDir/{$source['sha256']}.json";
$downloaded = false;
if ($specArg !== null) {
    $specText = @file_get_contents($specArg);
    if ($specText === false) {
        fail("Couldn't read $specArg");
    }
} elseif (is_file($cached) && hash_file('sha256', $cached) === $source['sha256']) {
    $specText = (string) file_get_contents($cached);
} else {
    // Guzzle, which the SDK already needs, works with or without the curl extension.
    require "$root/vendor/autoload.php";
    try {
        $specText = (string) (new GuzzleHttp\Client(['timeout' => 60]))->get($source['url'])->getBody();
    } catch (GuzzleHttp\Exception\GuzzleException $error) {
        fail("Couldn't download {$source['url']}: {$error->getMessage()}");
    }
    $downloaded = true;
}
$spec = json_decode($specText, true, 512, JSON_THROW_ON_ERROR);
// Checked before generating. A mismatch means source.json was only partly updated, so the
// record of what was generated from can't silently drift.
$sha256 = hash('sha256', $specText);
if ($specArg === null && ($source['sha256'] !== $sha256 || $source['version'] !== $spec['info']['version'])) {
    fail("{$source['url']} doesn't match spec/source.json. Set its version to {$spec['info']['version']} and its sha256 to $sha256.");
}
// Also over a cached copy that didn't match, such as one cut short, which was read past.
if ($downloaded) {
    @mkdir($cacheDir, 0777, true);
    file_put_contents($cached, $specText);
}
$specName = $specArg ?? $source['url'];

