$removed = array_values(array_diff($existingModels, array_keys($outputs)));

if ($check) {
    $stale = $removed;
    foreach ($outputs as $path => $content) {
        if (! is_file("$root/$path") || file_get_contents("$root/$path") !== $content) {
            $stale[] = $path;
        }
    }
    if ($stale !== []) {
        sort($stale);
        fail("Out of date with $specName: " . implode(', ', $stale) . '. Run `composer codegen`.');
    }
